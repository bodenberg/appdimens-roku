#!/usr/bin/env python3
"""Generates source/AppDimensTokens.brs: one method per token <prefix><s|h|w><dp|sp|em>[a|i|ia]
(432 methods) installed on every AppDimens instance. Other tokens (inverters, Px) go through
ad.resolve(token, v). Run after changing the token list."""
import os
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PREFIXES = ["", "a", "p", "pw", "f", "i", "log", "dg", "pr", "ft", "fl", "d"]
AXES = [("s", 0), ("h", 1), ("w", 2)]
KINDS = ["dp", "sp", "em"]
FLAGS = [("", 0), ("a", 1), ("i", 2), ("ia", 3)]
names, funcs = [], []
for si, p in enumerate(PREFIXES):
    for ax, v in AXES:
        for k in KINDS:
            for fl, f in FLAGS:
                tok = p + ax + k + fl
                slot = v * 4 + f
                fn = "AppDimens__T_" + tok
                mul = " * m.fontScale" if k == "sp" else ""
                funcs.append("function %s(v as float) as float\n    t = m.t[%d]\n    if t = invalid then t = m.row(%d)\n"
                             "    return v * t[%d]%s\nend function\n" % (fn, si, si, slot, mul))
                names.append((tok, fn))
low = [n.lower() for n, _ in names]
assert len(set(low)) == len(low), "case-insensitive clash"
out = ["' Generated by tools/gen_tokens.py — do not edit.",
       "' %d token methods: ad.sdp(v), ad.asdpa(v), ad.logssp(v), ad.ftwem(v) …" % len(names), "",
       "sub AppDimens_InstallTokens(ad as object)"]
out += ["    ad.%s = %s" % (n, fn) for n, fn in names]
out += ["end sub", ""]
import sys
text = "\n".join(out) + "\n" + "\n".join(funcs)
dst = os.path.join(ROOT, "source", "AppDimensTokens.brs")
if "--check" in sys.argv:
    if open(dst).read() != text:
        sys.exit("source/AppDimensTokens.brs is stale: run python3 tools/gen_tokens.py")
    print("tokens up to date (%d)" % len(names))
else:
    open(dst, "w").write(text)
    print(len(names), "tokens")
